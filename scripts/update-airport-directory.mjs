import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const sourceUrl = "https://davidmegginson.github.io/ourairports-data/airports.csv";
const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(repositoryRoot, "src/lib/airport-directory.generated.ts");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];

    if (quoted) {
      if (character === '"' && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (character === '"') {
        quoted = false;
      } else {
        field += character;
      }
    } else if (character === '"') {
      quoted = true;
    } else if (character === ",") {
      row.push(field);
      field = "";
    } else if (character === "\n") {
      row.push(field.replace(/\r$/, ""));
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += character;
    }
  }

  if (field || row.length > 0) {
    row.push(field.replace(/\r$/, ""));
    rows.push(row);
  }

  return rows;
}

function clean(value) {
  return value.trim().replace(/\s+/g, " ");
}

const localSourcePath = process.argv[2];
const sourceText = localSourcePath
  ? await readFile(path.resolve(localSourcePath), "utf8")
  : await (async () => {
      const response = await fetch(sourceUrl);
      if (!response.ok) {
        throw new Error(`Airport dataset download failed: ${response.status} ${response.statusText}`);
      }
      return response.text();
    })();

const rows = parseCsv(sourceText);
const headers = rows.shift();
if (!headers) throw new Error("Airport dataset has no header row");

const column = Object.fromEntries(headers.map((header, index) => [header, index]));
const countryNames = new Intl.DisplayNames(["en"], { type: "region" });
const typePriority = new Map([
  ["large_airport", 4],
  ["medium_airport", 3],
  ["small_airport", 2],
  ["seaplane_base", 1],
  ["heliport", 0],
]);
const airportsByCode = new Map();

for (const row of rows) {
  const code = clean(row[column.iata_code] ?? "").toUpperCase();
  const type = clean(row[column.type] ?? "");
  if (!/^[A-Z]{3}$/.test(code) || row[column.scheduled_service] !== "yes" || type === "closed") {
    continue;
  }

  const countryCode = clean(row[column.iso_country] ?? "").toUpperCase();
  const record = {
    code,
    name: clean(row[column.name] ?? ""),
    municipality: clean(row[column.municipality] ?? ""),
    country: countryNames.of(countryCode) ?? countryCode,
    keywords: clean(row[column.keywords] ?? ""),
    priority: typePriority.get(type) ?? -1,
  };
  const current = airportsByCode.get(code);
  if (!current || record.priority > current.priority) airportsByCode.set(code, record);
}

const records = [...airportsByCode.values()]
  .sort((left, right) => left.code.localeCompare(right.code))
  .map(({ code, name, municipality, country, keywords }) => [
    code,
    name,
    municipality,
    country,
    keywords,
  ]);

if (records.length < 4_000 || !records.some(([code]) => code === "YHZ")) {
  throw new Error("Airport dataset validation failed: expected 4,000+ records including YHZ");
}
const serializedRecords = JSON.stringify(records).replaceAll("],[", "],\n  [");

const generated = `// Generated by scripts/update-airport-directory.mjs from OurAirports.\n` +
  `// Source data is public domain: https://ourairports.com/data/\n` +
  `// Includes active airports with scheduled service and a three-letter IATA code.\n` +
  `export type AirportDirectoryRecord = readonly [\n` +
  `  code: string,\n  name: string,\n  municipality: string,\n  country: string,\n  keywords: string,\n];\n\n` +
  `export const airportDirectoryRecords: readonly AirportDirectoryRecord[] = [\n  ${serializedRecords.slice(1, -1)}\n];\n`;

await writeFile(outputPath, generated, "utf8");
console.log(`Wrote ${records.length} airport records to ${path.relative(repositoryRoot, outputPath)}`);
